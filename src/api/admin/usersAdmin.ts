/**
 * Users CRUD operations for public.users profile table
 *
 * IMPORTANT: USER TYPES
 * =====================
 * 1. AUTHENTICATED USERS:
 *    - Have accounts in auth.users (created via Supabase Auth sign-up/login)
 *    - Have profiles in public.users where id = auth.uid()
 *    - Profile is auto-created by ensureUserProfile() in auth.ts
 *    - Can have admin roles in user_roles table
 *
 * 2. GUEST USERS:
 *    - Do NOT have auth accounts
 *    - Have profiles in public.users with generated UUIDs
 *    - Created during checkout (checkout.js) or manually via AdminAccounts
 *    - Cannot become admins (no auth account = no admin access possible)
 *    - Can be associated with orders
 *
 * IMPORTANT NOTE ON ID:
 * ====================
 * - For authenticated users: id is set by ensureUserProfile() to auth.uid()
 * - For guest users: id is auto-generated by database
 * - createUser() does NOT set id, allowing database to generate it (for guests)
 * - Never manually set id = some value in createUser()
 */

import { supabase } from '../supabaseClient';
import type { UserRow } from './types';

/**
 * Users CRUD operations
 */

export async function listUsers(): Promise<UserRow[]> {
  const { data, error } = await supabase
    .from('users')
    .select('*')
    .order('created_at', { ascending: false });

  if (error) {
    throw new Error(`Failed to list users: ${error.message}`);
  }

  return data || [];
}

export async function getUserById(id: string): Promise<UserRow> {
  const { data, error } = await supabase.from('users').select('*').eq('id', id).single();

  if (error) {
    throw new Error(`Failed to get user: ${error.message}`);
  }

  if (!data) {
    throw new Error('User not found');
  }

  return data;
}

export async function createUser(payload: Omit<UserRow, 'id' | 'created_at'>): Promise<UserRow> {
  const { data, error } = await supabase.from('users').insert([payload]).select().single();

  if (error) {
    throw new Error(`Failed to create user: ${error.message}`);
  }

  if (!data) {
    throw new Error('User creation returned no data');
  }

  return data;
}

export async function updateUser(
  id: string,
  patch: Partial<Omit<UserRow, 'id' | 'created_at'>>
): Promise<UserRow> {
  const { data, error } = await supabase.from('users').update(patch).eq('id', id).select();

  if (error) {
    // Check if it's an RLS policy error
    const msg = error.message?.toLowerCase() || '';
    const code = error.code || '';
    if (
      msg.includes('row-level security') ||
      msg.includes('permission denied') ||
      code === 'PGRST301' ||
      code === '42501'
    ) {
      throw new Error('Access denied: You may not have permissions to update user profiles.');
    }
    throw new Error(`Failed to update user: ${error.message}`);
  }

  if (!data || data.length === 0) {
    // If no rows returned, it might be an RLS block
    throw new Error(
      'Access denied: You may not have permissions to update user profiles, or the user does not exist.'
    );
  }

  return data[0];
}

export async function removeUser(id: string): Promise<void> {
  const { error } = await supabase.from('users').delete().eq('id', id);

  if (error) {
    throw new Error(`Failed to delete user: ${error.message}`);
  }
}

/**
 * Delete user profile row with cascade cleanup:
 * 1. Delete user_roles where user_id matches
 * 2. Update orders to set user_id to null
 * 3. Delete from users
 */
export async function deleteUserProfileCascade(userId: string): Promise<void> {
  // Step 1: Delete user roles
  const { error: rolesError } = await supabase.from('user_roles').delete().eq('user_id', userId);

  if (rolesError) {
    const isRLSError =
      rolesError.message?.toLowerCase().includes('row-level security') ||
      rolesError.code === 'PGRST301' ||
      rolesError.message?.toLowerCase().includes('permission denied') ||
      rolesError.code === '42501';

    if (isRLSError) {
      throw new Error('Access denied: You may not have permissions to delete user roles.');
    }
    throw new Error(`Failed to delete user roles: ${rolesError.message}`);
  }

  // Step 2: Disassociate orders
  const { error: ordersError } = await supabase
    .from('orders')
    .update({ user_id: null })
    .eq('user_id', userId);

  if (ordersError) {
    const isRLSError =
      ordersError.message?.toLowerCase().includes('row-level security') ||
      ordersError.code === 'PGRST301' ||
      ordersError.message?.toLowerCase().includes('permission denied') ||
      ordersError.code === '42501';

    if (isRLSError) {
      throw new Error('Access denied: You may not have permissions to update orders.');
    }
    throw new Error(`Failed to disassociate orders: ${ordersError.message}`);
  }

  // Step 3: Delete user profile row
  const { error: userError } = await supabase.from('users').delete().eq('id', userId);

  if (userError) {
    const isRLSError =
      userError.message?.toLowerCase().includes('row-level security') ||
      userError.code === 'PGRST301' ||
      userError.message?.toLowerCase().includes('permission denied') ||
      userError.code === '42501';

    if (isRLSError) {
      throw new Error('Access denied: You may not have permissions to delete user profiles.');
    }
    throw new Error(`Failed to delete user profile: ${userError.message}`);
  }
}

/**
 * Count orders for a user
 */
export async function countUserOrders(userId: string): Promise<number> {
  const { count, error } = await supabase
    .from('orders')
    .select('*', { count: 'exact', head: true })
    .eq('user_id', userId);

  if (error) {
    throw new Error(`Failed to count orders: ${error.message}`);
  }

  return count || 0;
}

export default {
  listUsers,
  getUserById,
  createUser,
  updateUser,
  removeUser,
  deleteUserProfileCascade,
  countUserOrders,
};
